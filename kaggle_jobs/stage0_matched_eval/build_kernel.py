"""
Builds the Stage 0 matched-evaluation Kaggle kernel.

The hardened evaluator (kaggle_jobs/calibration_benchmark/evaluate_phase4d_adaptive_area.py) is embedded
byte-for-byte, minus its `if __name__ == "__main__"` trailer, so every model is scored by the exact code that
produced the Phase 5A-R numbers. A thin wrapper then:
  * pins ultralytics==8.4.174 before the evaluator imports it,
  * locates each checkpoint by SHA-256 (no filename auto-discovery),
  * runs the evaluator once per checkpoint into its own output folder,
  * streams every raw full-frame and crop detection (conf >= 0.01) to raw_detections.jsonl.gz, so later
    policy and threshold work is CPU-only.

Only the BDD100K val split is read. The test split is never touched.

Usage: python kaggle_jobs/stage0_matched_eval/build_kernel.py
Push:  kaggle kernels push -p kaggle_jobs/stage0_matched_eval/kernel
"""

import hashlib
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
EVALUATOR = HERE.parent / "calibration_benchmark" / "evaluate_phase4d_adaptive_area.py"
TRAILER = 'if __name__ == "__main__":\n    main()\n'
OUT_DIR = HERE / "kernel"
OUT_FILE = OUT_DIR / "stage0_matched_eval.py"

HEADER = '''"""
RoadSentinel Stage 0 — Matched-Policy Evaluation (GENERATED by build_kernel.py; do not edit).
Embedded evaluator: evaluate_phase4d_adaptive_area.py  sha256={sha}
Checkpoints: original YOLO11s, Phase 5A-U, Phase 5A-R. Split: BDD100K val only.
"""
import subprocess as _sp, sys as _sys
try:
    import ultralytics as _u
    _ok = _u.__version__ == "8.4.174"
except ImportError:
    _ok = False
if not _ok:
    _sp.check_call([_sys.executable, "-m", "pip", "install", "-q", "ultralytics==8.4.174"])

# ======================= BEGIN EMBEDDED EVALUATOR (unmodified) =======================
'''

WRAPPER = '''
# ======================= END EMBEDDED EVALUATOR =======================

import gzip as _gzip
import platform as _platform

EVALUATOR_SHA256 = "{sha}"
STAGE0_MODELS = [
    ("base_yolo11s", "A4747292648F37F68AB997BEA65A36391C41356F35E309A9F3D2EB1D3EA8D8E3"),
    ("phase5a_u",    "BB1823C6190E28CB56C12B549B0D1233B7DE6CF1B8624B1ED02378B42BB693E5"),
    ("phase5a_r",    "EDCCA4BF03CEC24A4E9D4EEEA524A63FBFD75E40E37359E106264F12A1B447F0"),
]
_raw_sink = None
_evaluator_fuse = baseline_fuse_and_deduplicate


def baseline_fuse_and_deduplicate(full_frame_dets, crop_dets, iou_thresh=0.50):
    """Records raw detections, then defers to the unmodified evaluator fusion."""
    if _raw_sink is not None:
        for d in full_frame_dets + crop_dets:
            _raw_sink.write(json.dumps({{
                "img": d["img_name"], "src": d["source"], "cls": d["class_name"],
                "conf": round(float(d["conf"]), 5), "box": [round(float(v), 2) for v in d["box"]],
            }}) + "\\n")
    return _evaluator_fuse(full_frame_dets, crop_dets, iou_thresh)


def _sha256(p):
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest().upper()


def stage0():
    global _raw_sink
    root = Path("/kaggle/working/stage0")
    root.mkdir(parents=True, exist_ok=True)
    by_sha = {{_sha256(p): p for p in Path("/kaggle/input").rglob("*.pt")}}
    missing = [n for n, s in STAGE0_MODELS if s not in by_sha]
    assert not missing, f"checkpoints not found by sha256: {{missing}}"

    manifest = {{
        "evaluator_sha256": EVALUATOR_SHA256,
        "ultralytics": ultralytics.__version__, "torch": torch.__version__,
        "gpu": torch.cuda.get_device_name(0) if torch.cuda.is_available() else "CPU",
        "platform": _platform.platform(), "split": "BDD100K val only (test quarantined)",
        "models": {{}},
    }}
    for name, sha in STAGE0_MODELS:
        out = root / name
        out.mkdir(exist_ok=True)
        print(f"\\n##### Stage 0: {{name}} ({{by_sha[sha]}})", flush=True)
        t0 = time.time()
        saved_stdout, saved_argv = sys.stdout, sys.argv
        _raw_sink = _gzip.open(out / "raw_detections.jsonl.gz", "wt", encoding="utf-8")
        try:
            sys.argv = [saved_argv[0], "--weights", str(by_sha[sha]), "--out_dir", str(out)]
            main()
        finally:
            _raw_sink.close()
            _raw_sink = None
            sys.stdout, sys.argv = saved_stdout, saved_argv
        manifest["models"][name] = {{"sha256": sha, "path": str(by_sha[sha]), "seconds": round(time.time() - t0, 1)}}
        (root / "stage0_manifest.json").write_text(json.dumps(manifest, indent=2))
    print(json.dumps(manifest, indent=2))


if __name__ == "__main__":
    stage0()
'''

METADATA = {
    "id": "hardikgautam25/roadsentinel-stage-0-matched-evaluation",
    "title": "RoadSentinel Stage 0 Matched Evaluation",
    "code_file": "stage0_matched_eval.py",
    "language": "python",
    "kernel_type": "script",
    "is_private": "true",
    "enable_gpu": "true",
    "enable_tpu": "false",
    "enable_internet": "true",
    "machine_shape": "NvidiaTeslaT4",
    "dataset_sources": ["a7madmostafa/bdd100k-yolo", "hardikgautam25/roadsentinel-weights"],
    "competition_sources": [],
    "kernel_sources": [
        "hardikgautam25/roadsentinel-phase-5a-vru-model-training",
        "hardikgautam25/roadsentinel-phase-5a-r-vru-weighted",
    ],
    "model_sources": [],
}


def main():
    src = EVALUATOR.read_text(encoding="utf-8")
    assert src.endswith(TRAILER), "evaluator trailer changed; update build_kernel.py"
    sha = hashlib.sha256(EVALUATOR.read_bytes()).hexdigest().upper()
    OUT_DIR.mkdir(exist_ok=True)
    OUT_FILE.write_text(HEADER.format(sha=sha) + src[: -len(TRAILER)] + WRAPPER.format(sha=sha), encoding="utf-8")
    (OUT_DIR / "kernel-metadata.json").write_text(json.dumps(METADATA, indent=2) + "\n")
    print(f"wrote {OUT_FILE} (evaluator sha256 {sha})")


if __name__ == "__main__":
    main()
